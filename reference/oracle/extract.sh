#!/bin/sh
# Regenerates generated/ from the original MMANA C++Builder sources.
# Everything under generated/ is copied verbatim (by line range) so the oracle
# runs the original algorithms, not a re-implementation.
#
# usage: ./extract.sh <path-to-MMANA-source>   (pinned to MMANA commit dfa4228)
set -eu

SRC=${1:?usage: extract.sh <path-to-MMANA-source>}
HERE=$(cd "$(dirname "$0")" && pwd)
OUT="$HERE/generated"
mkdir -p "$OUT"

range() { sed -n "$2,$3p" "$SRC/$1"; }

{
	echo "// GENERATED by extract.sh from MMANA ComLib.h (commit dfa4228). Do not edit."
	echo "#ifndef ComLibH"
	echo "#define ComLibH"
	echo "#include \"vcl_shim.h\""
	range ComLib.h 29 247
	range ComLib.h 337 400
	range ComLib.h 461 499    # CTextString
	range ComLib.h 687 879
	range ComLib.h 1016 1179  # CWGroup, CWGroupList (element editing)
	range ComLib.h 1183 1354  # AVAL, ATRG, MVAL, CACal (optimisation)
	# function declarations used by the extracted code
	for r in "253 253" "265 268" "271 273" "276 280" "282 282" "287 298" "302 305" "316 319" "321 322" "328 328"; do
		range ComLib.h $r
	done
	echo "#endif"
} > "$OUT/ComLib.h"

{
	echo "// GENERATED by extract.sh from MMANA ComLib.cpp (commit dfa4228). Do not edit."
	echo "#include \"ComLib.h\""
	echo "#include \"mininec3.h\""
	range ComLib.cpp 448 487    # CalcSWR, CalcParaZ
	range ComLib.cpp 546 597    # SkipSpace, StrDlm
	range ComLib.cpp 690 1313   # segmentation, combined wires, pulse names
	range ComLib.cpp 1697 1999  # expression evaluator, WriteCur
	range ComLib.cpp 2010 2142  # Teira, GetWireRoss
	range ComLib.cpp 2243 2267  # AdjPdef
	range ComLib.cpp 2313 2499  # CRes pattern / gain / F/B
	range ComLib.cpp 2637 2657  # CRes current
} > "$OUT/comlib_extract.cpp"

{
	echo "// GENERATED by extract.sh from MMANA ComLib.cpp (commit dfa4228). Do not edit."
	echo "#include \"ComLib.h\""
	range ComLib.cpp 346 362    # RoundUp(d, s)
	range ComLib.cpp 3169 4505  # CWGroup, CWGroupList
} > "$OUT/cwgroup_extract.cpp"

{
	echo "// GENERATED by extract.sh from MMANA ComLib.cpp and Main.cpp (commit dfa4228). Do not edit."
	echo "#include \"ComLib.h\""
	echo "#include \"mininec3.h\""
	echo "#include \"Main.h\""
	range ComLib.cpp 364 383    # RoundUpStr, GetNormal
	range ComLib.cpp 490 514    # GetDeg
	range ComLib.cpp 1510 1563  # AdjWireChen, GetWirePoll
	range ComLib.cpp 2545 2554  # ToFix
	range ComLib.cpp 2767 2792  # CRes::CopyLastRes
	range ComLib.cpp 4507 5520  # CACal (without DispStat)
	range Main.cpp 2762 2918    # CACal::Exec
} > "$OUT/cacal_extract.cpp"

{
	echo "// GENERATED by extract.sh from MMANA ACalBox.cpp (commit dfa4228). Do not edit."
	echo "#include \"ACalBox.h\""
	range ACalBox.cpp 716 947   # insert, delete, all elements
	range ACalBox.cpp 1036 1262 # automatic links of wires and loads
	range ACalBox.cpp 1299 1328 # element links
} > "$OUT/acalbox_extract.cpp"

# The one change to the original's arithmetic: the distance ratio must pass
# 1.1, 6 or 10 by a margin before the exact kernel or the full order of
# integration is given up. On a regular grid the ratio lands on a threshold
# and the rounding of the coordinates chose the side (|Z| up to 0.47 % apart
# for coordinates an ulp apart); the port does the same (ORDER_MARGIN in
# crates/mmana-core/src/engine/kernel.rs).
sed -e 's/if( T > 1\.1 ) goto L165;/if( T > 1.1*(1.0+1e-9) ) goto L165;/' \
	-e 's/if( T > 6 ) L=3;/if( T > 6*(1.0+1e-9) ) L=3;/' \
	-e 's/if( T > 10 ) L=1;/if( T > 10*(1.0+1e-9) ) L=1;/' \
	"$SRC/mininec3.cpp" > "$OUT/mininec3.cpp"
[ "$(grep -c '(1.0+1e-9)' "$OUT/mininec3.cpp")" = 3 ] || { echo "mininec3.cpp: the integration-order patch did not apply" >&2; exit 1; }
cp "$SRC/mininec3.h" "$OUT/mininec3.h"
echo "extracted into $OUT"
