#!/bin/sh
# Regenerates generated/ from the original MMANA C++Builder sources.
# Everything under generated/ is copied verbatim (by line range) so the oracle
# runs the original algorithms, not a re-implementation.
#
# usage: ./extract.sh <path-to-MMANA-source>   (pinned to MMANA commit dfa4228)
set -eu

SRC=${1:?usage: extract.sh <path-to-MMANA-source>}
HERE=$(cd "$(dirname "$0")" && pwd)
OUT="$HERE/generated"
mkdir -p "$OUT"

range() { sed -n "$2,$3p" "$SRC/$1"; }

{
	echo "// GENERATED by extract.sh from MMANA ComLib.h (commit dfa4228). Do not edit."
	echo "#ifndef ComLibH"
	echo "#define ComLibH"
	echo "#include \"vcl_shim.h\""
	range ComLib.h 29 247
	range ComLib.h 337 400
	range ComLib.h 461 499    # CTextString
	range ComLib.h 687 879
	# function declarations used by the extracted code
	for r in "253 253" "271 272" "276 279" "287 298" "316 319" "321 322" "328 328"; do
		range ComLib.h $r
	done
	echo "#endif"
} > "$OUT/ComLib.h"

{
	echo "// GENERATED by extract.sh from MMANA ComLib.cpp (commit dfa4228). Do not edit."
	echo "#include \"ComLib.h\""
	echo "#include \"mininec3.h\""
	range ComLib.cpp 448 487    # CalcSWR, CalcParaZ
	range ComLib.cpp 546 597    # SkipSpace, StrDlm
	range ComLib.cpp 690 1313   # segmentation, combined wires, pulse names
	range ComLib.cpp 1697 1999  # expression evaluator, WriteCur
	range ComLib.cpp 2010 2142  # Teira, GetWireRoss
	range ComLib.cpp 2243 2267  # AdjPdef
	range ComLib.cpp 2313 2499  # CRes pattern / gain / F/B
	range ComLib.cpp 2637 2657  # CRes current
} > "$OUT/comlib_extract.cpp"

cp "$SRC/mininec3.cpp" "$OUT/mininec3.cpp"
cp "$SRC/mininec3.h" "$OUT/mininec3.h"
echo "extracted into $OUT"
